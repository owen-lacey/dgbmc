#!/usr/bin/env node

/**
 * Build script to convert CSV files to embedded TypeScript data.
 * This runs before the Next.js build to bundle the graph data directly
 * in the JavaScript, preventing exposure of raw CSV files.
 */

const fs = require('fs');
const path = require('path');
const Papa = require('papaparse');

const RECOGNIZABILITY = parseInt(process.env.NEXT_PUBLIC_RECOGNIZABILITY || '10', 10);

const dataDir = path.join(__dirname, '..', 'data');
const outputPath = path.join(__dirname, '..', 'lib', 'graph-data.generated.ts');

const nodesPath = path.join(dataDir, `nodes_${RECOGNIZABILITY}.csv`);
const edgesPath = path.join(dataDir, `edges_${RECOGNIZABILITY}.csv`);

console.log(`Generating graph data for recognizability level ${RECOGNIZABILITY}...`);
console.log(`Reading nodes from: ${nodesPath}`);
console.log(`Reading edges from: ${edgesPath}`);

// Read CSV files
const nodesText = fs.readFileSync(nodesPath, 'utf-8');
const edgesText = fs.readFileSync(edgesPath, 'utf-8');

// Parse nodes CSV
const nodesParsed = Papa.parse(nodesText, {
  header: true,
  dynamicTyping: true,
  skipEmptyLines: true,
});

// Parse edges CSV
const edgesParsed = Papa.parse(edgesText, {
  header: true,
  dynamicTyping: true,
  skipEmptyLines: true,
});

// Transform nodes to graph format
const graphNodes = nodesParsed.data.map((actor) => ({
  id: actor.id,
  label: actor.name,
  recognizability: actor.Recognizability,
  movieCount: actor.movie_count,
}));

// Transform edges to graph format
// Note: Some movie titles like "1408" get parsed as numbers by dynamicTyping, so we ensure strings
const graphEdges = edgesParsed.data.map((edge, index) => ({
  id: `e${index}`,
  source: String(edge.Source),
  target: String(edge.Target),
  label: String(edge.movie_title),
  movieId: edge.movie_id,
  releaseDate: edge.release_date,
}));

const graphData = {
  nodes: graphNodes,
  edges: graphEdges,
};

// Generate TypeScript file
const tsContent = `// AUTO-GENERATED FILE - DO NOT EDIT
// Generated by scripts/generate-graph-data.js
// Regenerate with: npm run generate-data

import { GraphData } from '@/types/graph';

/**
 * Pre-processed graph data embedded at build time.
 * This keeps the source CSV files private and bundles the data with the JavaScript.
 */
export const GRAPH_DATA: GraphData = ${JSON.stringify(graphData, null, 2)} as const;
`;

fs.writeFileSync(outputPath, tsContent, 'utf-8');

console.log(`Generated ${outputPath}`);
console.log(`  - ${graphNodes.length} nodes`);
console.log(`  - ${graphEdges.length} edges`);
